const UGC_CODES = ["hku", "cuhk", "hkust", "cityu", "polyu", "hkbu", "lingnan", "eduhk"];

let opportunities = [];
let tagFilter = "all";
let uniFilter = "all";
let query = "";
let lastTrigger = null;

function typeLabel(value) {
  if (value === "tuition_waiver") return "Tuition waiver";
  if (typeof value !== "string" || value.length === 0) return "";
  return value.charAt(0).toUpperCase() + value.slice(1);
}

function tagLabel(value) {
  return TAG_LABEL[value] || String(value || "");
}

function prefersReducedMotion() {
  return window.matchMedia("(prefers-reduced-motion: reduce)").matches;
}

function countUp(node, target) {
  if (!node) return;
  if (prefersReducedMotion()) {
    node.textContent = String(target);
    return;
  }
  const duration = 1100;
  const start = performance.now();
  function tick(now) {
    const progress = Math.min(1, (now - start) / duration);
    const eased = 1 - Math.pow(1 - progress, 3);
    node.textContent = String(Math.round(eased * target));
    if (progress < 1) requestAnimationFrame(tick);
    else node.textContent = String(target);
  }
  requestAnimationFrame(tick);
}

function pulse(el) {
  if (!el) return;
  el.classList.remove("is-pulsing");
  void el.offsetWidth;
  el.classList.add("is-pulsing");
}

function universityLabel(code) {
  const found = opportunities.find((item) => item.university_code === code);
  return found ? found.university : code;
}

function filtered() {
  return opportunities.filter((item) => {
    if (tagFilter !== "all" && item.match_tag !== tagFilter) return false;
    if (uniFilter !== "all" && item.university_code !== uniFilter) return false;
    if (!query) return true;
    const clues = Array.isArray(item.eligibility_clues) ? item.eligibility_clues.join(" ") : "";
    const haystack = `${item.name || ""} ${item.university || ""} ${clues}`.toLowerCase();
    return haystack.includes(query);
  });
}

function line(label, value) {
  const row = document.createElement("span");
  row.className = "line";
  const lab = document.createElement("span");
  lab.className = "line-label";
  lab.textContent = label;
  const val = document.createElement("span");
  const text = value == null ? "" : String(value);
  val.className = text === "unknown" ? "line-value unknown" : "line-value";
  val.textContent = text;
  row.append(lab, val);
  return row;
}

function cardElement(item, index, animate) {
  const article = document.createElement("article");
  article.className = animate ? "card enter" : "card";
  article.dataset.tag = item.match_tag || "";
  article.style.setProperty("--i", String(Math.min(index, 16)));

  const button = document.createElement("button");
  button.type = "button";
  button.className = "card-button";
  button.dataset.id = item.id;

  const tag = document.createElement("span");
  tag.className = "tag";
  tag.textContent = tagLabel(item.match_tag);

  const uni = document.createElement("span");
  uni.className = "uni";
  uni.textContent = item.university || "";

  const name = document.createElement("span");
  name.className = "name";
  name.textContent = item.name || "";

  const kind = document.createElement("span");
  kind.className = "type";
  kind.textContent = typeLabel(item.type);

  button.append(tag, uni, name, kind, line("Amount", item.amount), line("Deadline", item.deadline));

  if (item.match_tag === "weak" || item.match_tag === "out_of_scope") {
    const stamp = document.createElement("span");
    stamp.className = "stamp";
    stamp.textContent = item.match_tag === "weak" ? "Weak" : "Out of scope";
    button.appendChild(stamp);
  }

  article.appendChild(button);
  return article;
}

function render(options) {
  const animate = Boolean(options && options.animate);
  const list = filtered();
  const board = document.getElementById("board");
  const empty = document.getElementById("empty");
  const shown = document.getElementById("shown");
  board.replaceChildren();
  shown.textContent = list.length ? `${list.length} shown` : "";
  empty.hidden = list.length !== 0;
  const fragment = document.createDocumentFragment();
  list.forEach((item, index) => {
    fragment.appendChild(cardElement(item, index, animate));
  });
  board.appendChild(fragment);
}

function setPressed(container, value) {
  container.querySelectorAll(".filter").forEach((button) => {
    button.setAttribute("aria-pressed", button.dataset.value === value ? "true" : "false");
  });
}

function buildFilters() {
  const tagBox = document.getElementById("tag-filters");
  const uniBox = document.getElementById("uni-filters");
  tagBox.replaceChildren();
  uniBox.replaceChildren();

  TAGS.forEach(([value, label]) => {
    const count = value === "all"
      ? opportunities.length
      : opportunities.filter((item) => item.match_tag === value).length;
    const button = document.createElement("button");
    button.type = "button";
    button.className = "filter";
    button.dataset.value = value;
    button.textContent = `${label} ${count}`;
    button.setAttribute("aria-pressed", value === tagFilter ? "true" : "false");
    button.addEventListener("click", () => {
      if (tagFilter === value) return;
      tagFilter = value;
      setPressed(tagBox, tagFilter);
      pulse(button);
      pulse(document.getElementById("stat-strong"));
      render({ animate: true });
    });
    tagBox.appendChild(button);
  });

  const allUni = document.createElement("button");
  allUni.type = "button";
  allUni.className = "filter";
  allUni.dataset.value = "all";
  allUni.textContent = `All ${opportunities.length}`;
  allUni.setAttribute("aria-pressed", "true");
  allUni.addEventListener("click", () => {
    if (uniFilter === "all") return;
    uniFilter = "all";
    setPressed(uniBox, uniFilter);
    pulse(allUni);
    pulse(document.getElementById("stat-strong"));
    render({ animate: true });
  });
  uniBox.appendChild(allUni);

  UNIVERSITY_CODES.forEach((code) => {
    const count = opportunities.filter((item) => item.university_code === code).length;
    const button = document.createElement("button");
    button.type = "button";
    button.className = "filter";
    button.dataset.value = code;
    button.textContent = `${universityLabel(code)} ${count}`;
    button.setAttribute("aria-pressed", "false");
    button.addEventListener("click", () => {
      if (uniFilter === code) return;
      uniFilter = code;
      setPressed(uniBox, uniFilter);
      pulse(button);
      pulse(document.getElementById("stat-strong"));
      render({ animate: true });
    });
    uniBox.appendChild(button);
  });
}

function fillList(node, values) {
  node.replaceChildren();
  const items = Array.isArray(values) ? values : [];
  items.forEach((value) => {
    const li = document.createElement("li");
    li.textContent = String(value);
    node.appendChild(li);
  });
}

function setFact(id, value) {
  const node = document.getElementById(id);
  const text = value == null ? "" : String(value);
  node.textContent = text;
  node.classList.toggle("unknown", text === "unknown");
}

function openDetail(item, trigger) {
  lastTrigger = trigger || null;
  const detail = document.getElementById("detail");
  detail.dataset.id = item.id || "";
  document.getElementById("detail-kicker").textContent = `${item.university || ""} · ${tagLabel(item.match_tag)}`;
  document.getElementById("detail-title").textContent = item.name || "";
  document.getElementById("detail-type").textContent = typeLabel(item.type);
  fillList(document.getElementById("detail-clues"), item.eligibility_clues);
  setFact("detail-amount", item.amount);
  setFact("detail-amount-note", item.amount_note);
  setFact("detail-deadline", item.deadline);
  setFact("detail-deadline-note", item.deadline_note);
  document.getElementById("detail-login").textContent = item.login_required ? "yes" : "no";
  fillList(document.getElementById("detail-restrictions"), item.restrictions);
  document.getElementById("detail-rationale").textContent = item.match_rationale || "";

  const link = document.getElementById("detail-source");
  const url = typeof item.source_url === "string" ? item.source_url : "";
  if (/^https:\/\//.test(url)) {
    link.href = url;
  } else {
    link.removeAttribute("href");
  }
  document.getElementById("detail-url").textContent = url;

  document.getElementById("scrim").hidden = false;
  detail.hidden = false;
  document.body.classList.add("detail-open");
  detail.scrollTop = 0;
  document.getElementById("detail-close").focus();
}

function closeDetail() {
  document.getElementById("detail").hidden = true;
  document.getElementById("scrim").hidden = true;
  document.body.classList.remove("detail-open");
  if (lastTrigger && lastTrigger.isConnected) lastTrigger.focus();
  else document.getElementById("search").focus();
}

async function loadOpportunities() {
  try {
    const fetchOptions = {};
    if (typeof AbortSignal !== "undefined" && typeof AbortSignal.timeout === "function") {
      fetchOptions.signal = AbortSignal.timeout(2500);
    }
    const response = await fetch("../opportunities.json", fetchOptions);
    if (!response.ok) throw new Error("status");
    const data = await response.json();
    if (!data || !Array.isArray(data.opportunities) || data.opportunities.length === 0) {
      throw new Error("shape");
    }
    document.body.dataset.source = "fetch";
    return data.opportunities;
  } catch (err) {
    document.body.dataset.source = "embedded";
    return EMBEDDED_OPPORTUNITIES.slice();
  }
}

function start(list) {
  opportunities = list;
  const total = opportunities.length;
  const strong = opportunities.filter((item) => item.match_tag === "strong").length;
  const covered = UGC_CODES.filter((code) => opportunities.some((item) => item.university_code === code)).length;

  document.getElementById("stat-total").setAttribute("aria-label", `Opportunities ${total}`);
  document.getElementById("stat-strong").setAttribute("aria-label", `Strong matches ${strong}`);
  document.getElementById("stat-universities").setAttribute("aria-label", `Universities covered ${covered}/8`);

  countUp(document.querySelector("#stat-total .stat-value"), total);
  countUp(document.querySelector("#stat-strong .stat-value"), strong);
  countUp(document.querySelector("#stat-universities .stat-num"), covered);

  buildFilters();
  render({ animate: true });
  document.body.dataset.ready = "true";
  document.body.dataset.count = String(total);
}

function bind() {
  document.getElementById("search").addEventListener("input", (event) => {
    query = event.target.value.trim().toLowerCase();
    render({ animate: false });
  });

  document.getElementById("board").addEventListener("click", (event) => {
    const button = event.target.closest("button.card-button");
    if (!button) return;
    const item = opportunities.find((row) => row.id === button.dataset.id);
    if (item) openDetail(item, button);
  });

  document.getElementById("detail-close").addEventListener("click", closeDetail);
  document.getElementById("scrim").addEventListener("click", closeDetail);

  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape" && !document.getElementById("detail").hidden) closeDetail();
  });

  document.getElementById("detail").addEventListener("keydown", (event) => {
    if (event.key !== "Tab") return;
    const focusable = document.getElementById("detail").querySelectorAll("button, a[href]");
    if (!focusable.length) return;
    const first = focusable[0];
    const last = focusable[focusable.length - 1];
    if (event.shiftKey && document.activeElement === first) {
      event.preventDefault();
      last.focus();
    } else if (!event.shiftKey && document.activeElement === last) {
      event.preventDefault();
      first.focus();
    }
  });
}

bind();
loadOpportunities().then(start);
